const choose = (label: Label, locale: Locale) => label[locale === 'zh' ? 0 : 1];
function readableName(name: string): string {
  return name.replace(/([a-z\d])([A-Z])/gu, '$1 $2').replace(/([A-Z])([A-Z][a-z])/gu, '$1 $2')
    .replace(/[_-]+/gu, ' ').replace(/\s+/gu, ' ').trim();
}

/** Compact names for archived mathematical tasks, with no inferred success or cross-run relationship. */
export function archiveRoadmapTaskLabel(task: Task, locale: Locale): string {
  const theorem = task.theorem?.split('.').filter(Boolean).at(-1);
  if (theorem && theoremLabels[theorem]) return choose(theoremLabels[theorem], locale);
  if (researchLabels[task.id]) return choose(researchLabels[task.id], locale);
  if (/^capacity_/u.test(task.id)) {
    if (/Capacity exploration \(decomposition\)/u.test(task.objective)) return choose(['探索原题的分解路线', 'Explore a decomposition of the original goal'], locale);
    if (/Capacity exploration \(construction\)/u.test(task.objective)) return choose(['探索原题的构造与见证', 'Explore a construction or witness for the original goal'], locale);
    return choose(['探索另一条证明路线', 'Explore another proof route'], locale);
  }
  if (/^initial_research_/u.test(task.id)) {
    if (/central construction or quantitative estimate/u.test(task.objective)) return choose(['研究关键构造与定量估计', 'Investigate the key construction and estimates'], locale);
    if (/library connections: the exact existing lemmas/u.test(task.objective)) return choose(['核对已有引理与库接口', 'Check existing lemmas and library interfaces'], locale);
    return choose(['研究证明路线与可用引理', 'Investigate proof routes and available lemmas'], locale);
  }
  if (theorem) return readableName(theorem) || choose(['数学任务', 'Mathematical task'], locale);
  const original = /^initial_goal_(\d+)$/u.exec(task.id);
  if (original) return locale === 'zh' ? `原题目标 ${original[1]}` : `Original target ${original[1]}`;
  const name = task.id.replace(/[_-][a-f0-9]{16,}$/u, '');
  if (/^[a-f0-9]{8}(?:-[a-f0-9]{4}){3}-[a-f0-9]{12}$/iu.test(name) || !name)
    return choose(['研究任务', 'Research task'], locale);
  return readableName(name) || choose(['研究任务', 'Research task'], locale);
}
