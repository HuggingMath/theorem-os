#!/usr/bin/env bun
// Regenerate after changes to displayed library mathematics: bun scripts/generate-web-library-search.ts
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { installedLibraryDeclarations } from '../apps/web/installedLibraryDefinitions';
import { installedLibraryInterfaceSearchText } from '../apps/web/installedLibraryInterfaceSearch';
import { installedLibraryMathematics } from '../apps/web/installedLibraryMathematics';
import type { InstalledLibraryEntry, InstalledLibrarySearchIndex } from '../apps/web/installedLibraryTypes';
import { readLibraryCatalog } from '../src/solver/libraryCatalog';

const catalog = readLibraryCatalog(fileURLToPath(new URL('../resources/theorem-os-library/release/catalog.json', import.meta.url)));
const index: InstalledLibrarySearchIndex = { catalogDigest: catalog.identity.catalogDigest, modules: {} };
for (const file of catalog.moduleFiles) {
  const module = catalog.moduleMetadata(file), entries = module.entries as InstalledLibraryEntry[];
  const { definitions, contexts } = installedLibraryDeclarations(catalog.readModule(file).source, entries);
  const moduleImport = `import ${file.slice(0, -'.lean'.length).replaceAll('/', '.')}`;
  index.modules[file] = { sha256: module.sha256, entries: Object.fromEntries(entries.map(entry => [entry.name, {
    summary: installedLibraryMathematics(entry, moduleImport, definitions[entry.name], contexts[entry.name]).summary,
    text: installedLibraryInterfaceSearchText(entry, moduleImport, definitions[entry.name], contexts[entry.name]),
  }])) };
}
const output = fileURLToPath(new URL('../apps/web/installedLibrarySearchData.ts', import.meta.url));
fs.writeFileSync(output, '// Generated by bun scripts/generate-web-library-search.ts. Do not edit.\n'
  + 'import type { InstalledLibrarySearchIndex } from \'./installedLibraryTypes\';\n\n'
  + `export const installedLibrarySearchData: InstalledLibrarySearchIndex = ${JSON.stringify(index, null, 2)};\n`);
console.log(`Generated search metadata for ${catalog.moduleCount} modules / ${catalog.declarationCount} interfaces (${index.catalogDigest}).`);
